// One-off migration: backfill the extended Bill Detail fields onto every
// existing bill in src/data/seed/bills.js. The master-data generator only
// appends new records beyond the current count, so it can't retrofit the 200
// records already committed — this script does. Run via:
//
//     node scripts/add-bill-detail-fields.mjs
//
// Idempotent: re-running recomputes the same deterministic values.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { VENDORS } from "../src/data/seed/vendors.js";
import { BILLS } from "../src/data/seed/bills.js";
import { deriveBillDetailFields } from "./bill-detail-fields.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

const HEADER =
  `// AUTO-GENERATED by scripts/generate-master-data.mjs (deterministic, seed 20250424).\n` +
  `// AP bills. \`vendor\` references vendors.js by id. The first 8 records are\n` +
  `// hand-curated demo anchors that the JE generator references; the rest are\n` +
  `// synthetic but reference the same vendor + CoA universe.`;

const out = BILLS.map((b) => {
  const vendor = VENDORS.find((v) => v.id === b.vendor);
  const num = parseInt(String(b.id).replace(/\D/g, ""), 10) || 0;
  const derived = deriveBillDetailFields(b, vendor, num);
  // Keep items + audit last so the file stays readable.
  const { items, audit, ...head } = b;
  return { ...head, ...derived, items, audit };
});

const body = `${HEADER}\nexport const BILLS = [\n${
  out.map((r) => "  " + JSON.stringify(r).replace(/"([a-zA-Z_][a-zA-Z0-9_]*)":/g, "$1:")).join(",\n")
},\n];\n`;

fs.writeFileSync(path.join(ROOT, "src/data/seed/bills.js"), body);
console.log(`Backfilled ${out.length} bills with extended Bill Detail fields.`);
